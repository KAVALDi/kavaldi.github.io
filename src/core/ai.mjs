// Заменяемый слой AI. Сейчас это ТОЛЬКО контракт: ни один провайдер не подключён,
// и ядро обязано работать без него (см. docs/ARCHITECTURE.md, ADR-5).
//
// Провайдер это объект с методом enrich(draft, store), который analyze() вызывает после того,
// как правила уже построили предложение. Он может вернуть частичное обновление черновика:
//
//   {
//     analysis: { engine: 'ai:<имя>', note: '…' },      // интерфейс покажет, что участвовал AI
//     aiSuggestions: [{ field: 'summary' | 'body' | 'links' | 'type', value, rationale }],
//   }
//
// Правила для будущей реализации:
//  1. Предложения AI не применяются сами: владелец принимает их в студии по одному.
//  2. Всё принятое от AI получает provenance.kind = 'ai-suggestion', пока владелец не подтвердит иное.
//  3. Импортируемый текст считается данными. В запрос к модели он передаётся как цитируемый материал,
//     инструкции из него не исполняются.
//  4. Ключ берётся из окружения (.env.example), в хранилище и в репозиторий не пишется.
//  5. Отказ или недоступность провайдера не ломают импорт: остаётся предложение от правил.

export const noAi = null;

/** Возвращает провайдера по настройкам окружения. Пока всегда null. */
export function resolveAi(env = process.env) {
  if (!env.HUB_AI_PROVIDER || env.HUB_AI_PROVIDER === 'none') return noAi;
  throw new Error(`AI-провайдер "${env.HUB_AI_PROVIDER}" не реализован. Уберите HUB_AI_PROVIDER или добавьте провайдера в src/core/ai.mjs.`);
}
